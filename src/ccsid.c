/* ---- UTF-8 multibyte encoder (for non-ASCII Latin-1 → UTF-8) ---- */
static int latin1_to_utf8(uint8_t byte, uint8_t *out, size_t rem) {
    if (byte < 0x80) {
        if (rem < 1) return SDB2_ERR_TRUNC;
        out[0] = byte;
        return 1;
    }
    /* Latin-1 0x80–0xFF encodes as 2-byte UTF-8: 0xC2/0xC3 + continuation */
    if (rem < 2) return SDB2_ERR_TRUNC;
    out[0] = (uint8_t)(0xC0 | (byte >> 6));
    out[1] = (uint8_t)(0x80 | (byte & 0x3F));
    return 2;
}

/* ---- Public API ---- */

int ccsid_utf8_to_wire(int ccsid, const uint8_t *src, size_t src_len,
                       uint8_t *out, size_t out_cap) {
    size_t wi = 0;

    switch (ccsid) {
    case CCSID_UTF8:
        /* Identity: UTF-8 on the wire. */
        if (src_len > out_cap) return SDB2_ERR_TRUNC;
        memcpy(out, src, src_len);
        return (int)src_len;

    case CCSID_ASCII:
        /* ASCII: pass through bytes 0x00–0x7F; reject anything else. */
        if (src_len > out_cap) return SDB2_ERR_TRUNC;
        for (size_t i = 0; i < src_len; i++) {
            if (src[i] > 0x7F) return SDB2_ERR_UNSUPPORT;
            out[wi++] = src[i];
        }
        return (int)wi;

    case CCSID_EBCDIC:
    case CCSID_EBCDIC_US:
        /* Translate byte-by-byte via lookup table.
         * Input must be single-byte (Latin-1 or ASCII).  Multi-byte UTF-8
         * sequences that fall outside Latin-1 are unsupported for control
         * data (DRDA control fields only use the ASCII invariant anyway). */
        for (size_t i = 0; i < src_len; ) {
            uint8_t c = src[i];
            if (c < 0x80) {
                /* ASCII byte — direct lookup */
                if (wi >= out_cap) return SDB2_ERR_TRUNC;
                out[wi++] = ascii_to_ebcdic[c];
                i++;
            } else if ((c & 0xE0) == 0xC0 && i + 1 < src_len &&
                       (src[i+1] & 0xC0) == 0x80) {
                /* 2-byte UTF-8: decode to Latin-1 codepoint */
                uint32_t cp = ((uint32_t)(c & 0x1F) << 6) | (src[i+1] & 0x3F);
                if (cp > 0xFF) return SDB2_ERR_UNSUPPORT;
                if (wi >= out_cap) return SDB2_ERR_TRUNC;
                out[wi++] = ascii_to_ebcdic[cp];
                i += 2;
            } else {
                return SDB2_ERR_UNSUPPORT;
            }
        }
        return (int)wi;

    default:
        return SDB2_ERR_UNSUPPORT;
    }
}

int ccsid_wire_to_utf8(int ccsid, const uint8_t *src, size_t src_len,
                       uint8_t *out, size_t out_cap) {
    size_t wi = 0;

    switch (ccsid) {
    case CCSID_UTF8:
        if (src_len > out_cap) return SDB2_ERR_TRUNC;
        memcpy(out, src, src_len);
        return (int)src_len;

    case CCSID_ASCII:
        if (src_len > out_cap) return SDB2_ERR_TRUNC;
        for (size_t i = 0; i < src_len; i++) {
            if (src[i] > 0x7F) return SDB2_ERR_UNSUPPORT;
            out[wi++] = src[i];
        }
        return (int)wi;

    case CCSID_EBCDIC:
    case CCSID_EBCDIC_US: {
        /* EBCDIC → Latin-1 → UTF-8 */
        for (size_t i = 0; i < src_len; i++) {
            uint8_t latin1 = ebcdic_to_ascii[src[i]];
            int n = latin1_to_utf8(latin1, out + wi, out_cap - wi);
            if (n < 0) return n;
            wi += (size_t)n;
        }
        return (int)wi;
    }

    default:
        return SDB2_ERR_UNSUPPORT;
    }
}

int ccsid_put_string(buf_t *b, int ccsid, const char *str) {
    size_t len = strlen(str);
    int r = buf_ensure(b, len * 3); /* worst case: each byte → 3 UTF-8 bytes */
    if (r) return r;
    int n = ccsid_utf8_to_wire(ccsid, (const uint8_t *)str, len,
                                b->data + b->pos, b->cap - b->pos);
    if (n < 0) return n;
    b->pos += (size_t)n;
    return n;
}
